export type NativeCopyKey = keyof typeof copy.en;

export function nativeText(locale: NativeLocale | undefined, key: NativeCopyKey) {
  return copy[locale === 'ro' ? 'ro' : 'en'][key];
}

export function nativeLocale(locale: string | undefined): NativeLocale {
  return locale === 'ro' ? 'ro' : 'en';
}

export function nativeStatusLabel(locale: NativeLocale | undefined, label: string) {
  if (locale !== 'ro') return label;
  const normalized = label.toLowerCase();
  const translations: Record<string, string> = {
    active: 'Activ',
    approved: 'Aprobat',
    blocked: 'Blocat',
    cancelled: 'Anulat',
    complete: 'Finalizat',
    completed: 'Finalizat',
    'in progress': 'În lucru',
    'in production': 'În producție',
    draft: 'Ciornă',
    'to do': 'De făcut',
  };
  return translations[normalized] ?? label;
}
